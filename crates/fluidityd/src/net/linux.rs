use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use super::{Backend, run, run_with_input, state_file, state_files};
use crate::killswitch::{Rules, nft_rules as kill_switch_rules};
use crate::netconfig::{NetConfig, ResolvedDns};

const RESOLV_CONF: &str = "/etc/resolv.conf";
const KILL_SWITCH_TABLE: &str = "fluiditykillswitch";

pub struct LinuxBackend {
    state_dir: PathBuf,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct Saved {
    resolved_link: Option<String>,
    resolv_conf: Option<String>,
    nft_table: Option<String>,
}

fn resolved_available() -> bool {
    Path::new("/run/systemd/resolve").is_dir() && run("resolvectl", &["status", "--no-pager"]).is_ok()
}

fn table_name(id: &str) -> String {
    let safe: String = id
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .take(40)
        .collect();
    format!("fluidity_{safe}")
}

pub fn resolv_conf_text(cfg: &NetConfig) -> String {
    let mut text = String::from("# Generated by Fluidity\n");
    for server in cfg.servers.iter().take(3) {
        text.push_str(&format!("nameserver {server}\n"));
    }
    if !cfg.search_domains.is_empty() {
        text.push_str(&format!("search {}\n", cfg.search_domains.join(" ")));
    }
    text
}

pub fn nft_rules(table: &str, interface: &str) -> String {
    format!(
        "table inet {table} {{\n\
         \tchain output {{\n\
         \t\ttype filter hook output priority 0; policy accept;\n\
         \t\toifname \"lo\" accept\n\
         \t\toifname \"{interface}\" accept\n\
         \t\tip6 daddr {{ fe80::/10, ff00::/8 }} accept\n\
         \t\tmeta nfproto ipv6 drop\n\
         \t}}\n\
         }}\n"
    )
}

impl LinuxBackend {
    pub fn new(state_dir: &Path) -> Self {
        Self {
            state_dir: state_dir.to_path_buf(),
        }
    }

    fn apply_dns(&self, saved: &mut Saved, cfg: &NetConfig) -> Result<(), String> {
        let Some(mode) = cfg.dns else { return Ok(()) };
        if resolved_available() {
            let iface = cfg.interface.as_str();
            let mut dns_args = vec!["dns", iface];
            dns_args.extend(cfg.servers.iter().map(String::as_str));
            run("resolvectl", &dns_args)?;
            saved.resolved_link = Some(iface.to_string());
            let routing: Vec<String> = match mode {
                ResolvedDns::Full => std::iter::once("~.".to_string())
                    .chain(cfg.search_domains.iter().cloned())
                    .collect(),
                ResolvedDns::Split => cfg
                    .match_domains
                    .iter()
                    .map(|d| format!("~{d}"))
                    .chain(cfg.search_domains.iter().cloned())
                    .collect(),
            };
            let mut domain_args = vec!["domain", iface];
            domain_args.extend(routing.iter().map(String::as_str));
            run("resolvectl", &domain_args)?;
            let default_route = if mode == ResolvedDns::Full { "true" } else { "false" };
            run("resolvectl", &["default-route", iface, default_route])?;
            let _ = run("resolvectl", &["flush-caches"]);
            return Ok(());
        }
        if mode == ResolvedDns::Split {
            return Err("split DNS needs systemd-resolved".into());
        }
        let original = fs::read_to_string(RESOLV_CONF).unwrap_or_default();
        saved.resolv_conf = Some(original);
        fs::write(RESOLV_CONF, resolv_conf_text(cfg)).map_err(|e| format!("{RESOLV_CONF}: {e}"))
    }

    fn apply_ipv6_block(&self, saved: &mut Saved, id: &str, interface: &str) -> Result<(), String> {
        let table = table_name(id);
        run_with_input("nft", &["-f", "-"], &nft_rules(&table, interface))?;
        saved.nft_table = Some(table);
        Ok(())
    }

    fn persist(&self, id: &str, saved: &Saved) {
        let _ = fs::create_dir_all(&self.state_dir);
        if let Ok(json) = serde_json::to_vec(saved) {
            let _ = fs::write(state_file(&self.state_dir, id), json);
        }
    }

    fn undo(saved: &Saved) {
        if let Some(link) = &saved.resolved_link {
            let _ = run("resolvectl", &["revert", link]);
        }
        if let Some(original) = &saved.resolv_conf {
            let _ = fs::write(RESOLV_CONF, original);
        }
        if let Some(table) = &saved.nft_table {
            let _ = run("nft", &["delete", "table", "inet", table]);
        }
    }
}

impl Backend for LinuxBackend {
    fn apply(&self, id: &str, cfg: &NetConfig) -> Result<(), String> {
        self.revert(id);
        if cfg.is_empty() {
            return Ok(());
        }
        let mut saved = Saved::default();
        let result = self.apply_dns(&mut saved, cfg).and_then(|_| {
            if cfg.block_ipv6 {
                self.apply_ipv6_block(&mut saved, id, &cfg.interface)
            } else {
                Ok(())
            }
        });
        self.persist(id, &saved);
        result
    }

    fn revert(&self, id: &str) {
        let path = state_file(&self.state_dir, id);
        let Ok(data) = fs::read(&path) else { return };
        if let Ok(saved) = serde_json::from_slice::<Saved>(&data) {
            Self::undo(&saved);
        }
        let _ = fs::remove_file(path);
    }

    fn kill_switch(&self, rules: Option<&Rules>) -> Result<(), String> {
        match rules {
            Some(rules) => {
                let script = format!(
                    "add table inet {KILL_SWITCH_TABLE}\ndelete table inet {KILL_SWITCH_TABLE}\n{}",
                    kill_switch_rules(KILL_SWITCH_TABLE, rules)
                );
                run_with_input("nft", &["-f", "-"], &script).map(|_| ())
            }
            None => {
                let _ = run("nft", &["delete", "table", "inet", KILL_SWITCH_TABLE]);
                Ok(())
            }
        }
    }

    fn recover(&self) {
        let _ = run("nft", &["delete", "table", "inet", KILL_SWITCH_TABLE]);
        for path in state_files(&self.state_dir) {
            if let Ok(data) = fs::read(&path)
                && let Ok(saved) = serde_json::from_slice::<Saved>(&data)
            {
                Self::undo(&saved);
            }
            let _ = fs::remove_file(path);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_resolv_conf_and_rules() {
        let cfg = NetConfig {
            servers: vec!["10.0.0.1".into()],
            search_domains: vec!["corp".into()],
            ..NetConfig::default()
        };
        assert_eq!(
            resolv_conf_text(&cfg),
            "# Generated by Fluidity\nnameserver 10.0.0.1\nsearch corp\n"
        );
        assert!(nft_rules("fluidity_x", "tun0").contains("oifname \"tun0\" accept"));
    }
}
